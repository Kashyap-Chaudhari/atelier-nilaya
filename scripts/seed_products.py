def seed_database():
    print("Clearing existing products and categories...")
    JewelleryProduct.objects.all().delete()
    JewelleryCategory.objects.all().delete()

    total_prods = 0
    for cat_data in CATEGORIES_DATA:
        products_data = cat_data.pop('products')
        category, created = JewelleryCategory.objects.get_or_create(
            slug=cat_data['slug'],
            defaults=cat_data
        )
        print(f"Created category: {category.name}")

        for p_idx, prod_data in enumerate(products_data):
            prod_data['display_order'] = p_idx + 1
            prod = JewelleryProduct.objects.create(
                category=category,
                **prod_data
            )
            total_prods += 1
            print(f"  [{category.name}] Created product: {prod.name} ({prod.formatted_price})")

    print(f"\nSUCCESS! Seeded {JewelleryCategory.objects.count()} categories and {total_prods} products!")

if __name__ == '__main__':
    seed_database()
